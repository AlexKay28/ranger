"""Self-hosted agentic project-growth loop, as a runnable application.

This is the loop from docs/growth-log.md expressed in ranger calls: the
agent grows a target project by repeating, per cycle:

    survey   -> search  : baseline, rough edges, observed issues
    wish     -> ask     : five personas produce improvement wishes
    select   -> ask     : pick exactly ONE goal (best value/cost)
    contract -> ask     : freeze acceptance checks before any work
    do       -> do      : implement against the goal
    verify   -> tests   : run the goal's acceptance checks locally

Every cycle is appended as structured markdown to <target>/growth-loop-log.md,
which is the loop's only cross-cycle memory — the next cycle reads it first
(failing goals carry a penalty, passing ones are deduped).

Run from this directory (real agent runs — costs time and tokens):

    python growth_loop.py /path/to/project [cycles]

Guardrails kept from the protocol: one goal per cycle, frozen contract,
bounded retries per goal, no destructive git commands, honest outcomes
(pass/block/fail) recorded even when they are failures.
"""

import os
import subprocess
import sys
import time
from pathlib import Path

import ranger

DEFAULT_MODEL = "openrouter/anthropic/claude-sonnet-4.5"
DEFAULT_CYCLES = 3
MAX_ATTEMPTS_PER_GOAL = 2

PERSONAS = [
    "a newcomer evaluating this repo for adoption (trust signals, docs)",
    "a library user prototyping an agentic loop with this API",
    "an outside contributor making a first change",
    "a release manager caring about tests, packaging, CI",
    "a maintainer annoyed by small recurring friction",
]

LOG_NAME = "growth-loop-log.md"


def _seed_log(target: Path) -> None:
    log = target / LOG_NAME
    if not log.exists():
        log.write_text("# growth-loop log\n\nGenerated by examples/growth_loop.py.\n")


def _append_log(target: Path, text: str) -> None:
    with (target / LOG_NAME).open("a") as f:
        f.write(text)
        f.flush()


def run_acceptance_checks(target: Path, checks_cmd: str) -> tuple[bool, str]:
    """Run the contract's acceptance checks mechanically — never trust the
    implementer's word; pass/fail comes from the check command's exit code."""
    try:
        proc = subprocess.run(
            checks_cmd, shell=True, cwd=target,
            capture_output=True, text=True, timeout=600,
        )
        return proc.returncode == 0, (proc.stdout + proc.stderr).strip()[-2000:]
    except subprocess.TimeoutExpired:
        return False, "acceptance checks timed out"


def one_cycle(agent: ranger.Ranger, target: Path, n: int) -> str:
    memory = (target / LOG_NAME).read_text()

    # 1. survey + 2. persona wishes, deduped against the log's past work
    findings = agent.search("bugs, TODOs, missing docs, untested paths, rough edges")
    wishes = agent.ask(
        f"Project findings:\n{findings}\n\n"
        f"Growth log of previous cycles (already done — do not repeat these):\n{memory}\n\n"
        "You will now voice five personas, playing each one in turn:\n"
        + "\n".join(f"- {p}" for p in PERSONAS) + "\n\n"
        "As each persona, name ONE concrete improvement wish about the "
        "user-facing surface only. Then list all five as `WISH #n: ...` lines."
    )

    # 3. select ONE goal + 4. freeze the contract
    selection = agent.ask(
        f"Improvement wishes:\n{wishes}\n\nGrowth log (avoid repeats, penalize "
        f"previously failed goals):\n{memory}\n\n"
        "Pick the single best goal by value/cost across the wishes. Reply EXACTLY in this "
        "format, nothing else:\n"
        "GOAL: <one line>\n"
        "WHY: <one line>\n"
        "CHECKS_CMD: <single shell command whose exit code proves the goal is met>\n"
        "NON_GOALS: <comma list>"
    )
    print(f"[cycle {n}] selected:\n{selection}\n")
    checks_cmd = next(
        (ln.split("CHECKS_CMD:", 1)[1].strip() for ln in selection.splitlines()
         if ln.strip().startswith("CHECKS_CMD:")),
        "true",
    )

    # 5. bounded implement -> verify attempts (frozen contract, mechanical gate)
    outcome, evidence, attempt = "fail_budget", "", 0
    goal_line = next((ln for ln in selection.splitlines() if ln.startswith("GOAL:")), "GOAL: ?")
    for attempt in range(1, MAX_ATTEMPTS_PER_GOAL + 1):
        agent.do(f"{goal_line}\nDo the work now. Respect the non-goals.")
        passed, evidence = run_acceptance_checks(target, checks_cmd)
        if passed:
            outcome = "pass_merged"
            break
        if attempt < MAX_ATTEMPTS_PER_GOAL:
            agent.do(
                f"The acceptance check `{checks_cmd}` failed. Fix your previous "
                f"work: {goal_line}\n"
                "DO NOT weaken the check, change the goal, or git-reset anything.\n"
                f"Check output was:\n{evidence}"
            )

    # 6. append the honest record — failures included — as the loop's memory
    stamp = time.strftime("%Y-%m-%d %H:%M:%S")
    _append_log(
        target,
        f"\n## cycle {n} ({stamp})\n\n{selection}\n"
        f"- attempts: {attempt}, outcome: **{outcome}**\n"
        f"- checks: `{checks_cmd}`\n```\n{evidence[:1000]}\n```\n",
    )
    return outcome


def main() -> None:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    cycles = int(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_CYCLES
    _seed_log(target)
    agent = ranger.Ranger(cwd=target, timeout=900)
    for n in range(1, cycles + 1):
        print(f"=== growth cycle {n}/{cycles} on {target} ===")
        outcome = one_cycle(agent, target, n)
        print(f"[cycle {n}] outcome: {outcome}")
    print(f"log: {target / LOG_NAME}")


if __name__ == "__main__":
    main()


